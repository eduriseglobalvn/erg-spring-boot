package com.erg.ergspringboot.service.quiz.publish;

import com.erg.ergspringboot.service.quiz.publish.CompiledQuiz.CompiledQuestion;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.springframework.stereotype.Service;

/**
 * Publish gate (spec §8). Runs on {@code /validate} (no mutation) and again inside the {@code /publish}
 * transaction. Returns a flat list of errors keyed by a path so the FE can surface them inline; an empty
 * list means the draft is publishable.
 *
 * <p>Rules mirror spec §8: at least one auto-gradable question, every auto-gradable question has a solvable
 * answer key, likert is a survey, package points are generated by the compiler, and media
 * must be committed (no dangling/base64) — media resolution is checked by the publish service which has the
 * asset repository, so this stage focuses on question/answer integrity.
 */
@Service
public final class QuizValidationService {

    public record ValidationError(String path, String code, String message) {
    }

    public List<ValidationError> validate(CompiledQuiz compiled) {
        List<ValidationError> errors = new ArrayList<>();
        List<CompiledQuestion> questions = compiled.questions();

        long autoGradable = questions.stream().filter(CompiledQuestion::autoGradable).count();
        if (autoGradable == 0) {
            errors.add(new ValidationError("questions", "NO_GRADABLE_QUESTION",
                    "quiz must contain at least one auto-gradable question"));
        }

        for (CompiledQuestion question : questions) {
            String path = "questions[" + question.orderIndex() + "]";
            validateAnswerKey(question, path, errors);
        }
        return errors;
    }

    private void validateAnswerKey(CompiledQuestion question, String path, List<ValidationError> errors) {
        Map<String, Object> key = question.answerKey();
        switch (question.kind()) {
            case "single_choice", "true_false" -> {
                if (blank(key.get("correctChoiceId"))) {
                    errors.add(missing(path, "correct choice"));
                }
            }
            case "multiple_response" -> {
                if (emptyList(key.get("correctChoiceIds"))) {
                    errors.add(missing(path, "at least one correct choice"));
                }
            }
            case "short_answer" -> {
                if (emptyList(key.get("correctAnswers"))) {
                    errors.add(missing(path, "accepted answers"));
                }
            }
            case "numeric" -> {
                if (key.get("value") == null) {
                    errors.add(missing(path, "numeric value"));
                }
            }
            case "sequence" -> {
                if (emptyList(key.get("order"))) {
                    errors.add(missing(path, "correct order"));
                }
            }
            case "matching" -> {
                if (emptyList(key.get("pairs"))) {
                    errors.add(missing(path, "matching pairs"));
                }
            }
            case "fill_blank", "drag_words", "select_from_lists" -> {
                if (emptyList(key.get("blanks"))) {
                    errors.add(missing(path, "blank answers"));
                }
            }
            case "hotspot" -> {
                if (emptyList(key.get("regions"))) {
                    errors.add(missing(path, "correct region"));
                }
            }
            case "drag_drop" -> {
                if (emptyList(key.get("targets"))) {
                    errors.add(missing(path, "item targets"));
                }
            }
            case "essay" -> {
                // Manual grading; package points are generated by the compiler.
            }
            default -> {
                // likert_scale is a survey — no answer key required.
            }
        }
    }

    private ValidationError missing(String path, String what) {
        return new ValidationError(path + ".answerKey", "MISSING_ANSWER_KEY",
                "auto-gradable question is missing " + what);
    }

    private boolean blank(Object value) {
        return value == null || value.toString().isBlank();
    }

    private boolean emptyList(Object value) {
        return !(value instanceof List<?> list) || list.isEmpty();
    }
}
