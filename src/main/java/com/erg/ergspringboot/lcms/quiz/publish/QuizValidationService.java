package com.erg.ergspringboot.lcms.quiz.publish;

import com.erg.ergspringboot.lcms.quiz.publish.CompiledQuiz.CompiledQuestion;
import java.util.ArrayList;
import java.util.List;
import org.springframework.stereotype.Service;

/**
 * Publish gate (spec §8). Runs on {@code /validate} (no mutation) and again inside the {@code /publish}
 * transaction. Returns a flat list of errors keyed by a path so the FE can surface them inline; an empty
 * list means the draft is publishable.
 *
 * <p>Rules mirror spec §8: at least one auto-gradable question, every auto-gradable question has a solvable
 * answer key, likert is a survey, package points are generated by the compiler, and media
 * must be committed (no dangling/base64) — media resolution is checked by the publish service which has the
 * asset repository, so this stage focuses on question/answer integrity.
 */
@Service
public class QuizValidationService {

    public record ValidationError(String path, String code, String message) {
    }

    public List<ValidationError> validate(CompiledQuiz compiled) {
        List<ValidationError> errors = new ArrayList<>();
        List<CompiledQuestion> questions = compiled.questions();

        long autoGradable = questions.stream().filter(CompiledQuestion::autoGradable).count();
        if (autoGradable == 0) {
            errors.add(new ValidationError("questions", "NO_GRADABLE_QUESTION",
                    "quiz must contain at least one auto-gradable question"));
        }

        for (CompiledQuestion question : questions) {
            String path = "questions[" + question.orderIndex() + "]";
            validateAnswerKey(question, path, errors);
        }
        return errors;
    }

    private void validateAnswerKey(CompiledQuestion question, String path, List<ValidationError> errors) {
        String missing = QuestionKindRegistry.requireRuntimeKind(question.kind()).strategy()
                .missingAnswerKey(question.answerKey());
        if (missing != null) {
            errors.add(missing(path, missing));
        }
    }

    private ValidationError missing(String path, String what) {
        return new ValidationError(path + ".answerKey", "MISSING_ANSWER_KEY",
                "auto-gradable question is missing " + what);
    }
}
